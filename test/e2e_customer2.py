import asyncio
from playwright.async_api import async_playwright
from _env import URL, launch_opts
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(**launch_opts())
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        pg = await ctx.new_page()
        logs = []
        pg.on('console', lambda m: logs.append(m.type + ': ' + m.text) if m.type in ('error',) else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERROR: ' + str(e)))
        await pg.goto(URL + '#table-5')
        await pg.wait_for_timeout(4500)
        await pg.screenshot(path='shots/c4_hero.png', clip={'x':0,'y':0,'width':390,'height':300})
        await pg.click('a.cam')
        await pg.wait_for_timeout(2500)
        await pg.screenshot(path='shots/c5_ar_start.png')
        await pg.click('[data-start=virtual]')
        await pg.wait_for_timeout(2500)
        await pg.screenshot(path='shots/c6_ar_virtual.png')
        # swipe right -> next dish
        await pg.mouse.move(120, 420); await pg.mouse.down(); await pg.mouse.move(200, 425, steps=4); await pg.mouse.move(300, 425, steps=4); await pg.mouse.up()
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/c7_ar_swiped.png')
        await pg.click('.ar-card [data-a=add]')
        await pg.wait_for_timeout(600)
        await pg.click('.ar-cats button[data-cat="Desserts"]')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/c8_ar_desserts.png')
        # live camera (fake device)
        await pg.click('[data-a=mode]')
        await pg.wait_for_timeout(500)
        await pg.click('[data-start=live]')
        await pg.wait_for_timeout(3000)
        await pg.screenshot(path='shots/c9_ar_live.png')
        print('mode label:', await pg.inner_text('[data-a=mode]'))
        # close AR -> cart
        await pg.click('[data-a=cart]')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/c10_cart.png', full_page=True)
        # pay at counter
        await pg.click('[data-pm=counter]')
        await pg.click('[data-act=place]')
        await pg.wait_for_timeout(2500)
        await pg.screenshot(path='shots/c11_placed.png')
        await pg.click('[data-x]')
        await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/c12_bills.png')
        # second order with UPI
        await pg.goto(URL + '#menu'); await pg.wait_for_timeout(1500)
        await pg.click('button[data-inc="samosa"]'); await pg.click('button[data-inc="filter-kaapi"]')
        await pg.goto(URL + '#cart'); await pg.wait_for_timeout(1200)
        await pg.click('[data-pm=upi]'); await pg.click('[data-act=place]')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/c13_upi.png')
        await pg.click('.dialog-f .btn.saffron')
        await pg.wait_for_timeout(2000)
        # third order with card
        await pg.goto(URL + '#menu'); await pg.wait_for_timeout(1200)
        await pg.click('button[data-inc="donut"]')
        await pg.goto(URL + '#cart'); await pg.wait_for_timeout(1000)
        await pg.click('[data-pm=card]'); await pg.click('[data-act=place]')
        await pg.wait_for_timeout(800)
        await pg.fill('[data-cn]', '4000000000000002'); await pg.fill('[data-ce]', '1229'); await pg.fill('[data-cv]', '123')
        await pg.click('.dialog-f .btn.saffron'); await pg.wait_for_timeout(1800)
        await pg.screenshot(path='shots/c14_declined.png')
        await pg.fill('[data-cn]', '4111111111111111')
        await pg.click('.dialog-f .btn.saffron'); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='shots/c15_card_ok.png')
        await pg.click('[data-x]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/c16_bills3.png')
        await pg.click('.bill-row'); await pg.wait_for_timeout(800)
        await pg.click('[data-o=counter]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/c17_counter.png')
        orders = await pg.evaluate("Data.state.orders.map(o => [o.id, o.total, o.pay.method, o.pay.status, o.status, o.table, Object.keys(o.use).length])")
        print('ORDERS', orders)
        stock = await pg.evaluate("(() => { const m = Data.derived().stockMap; return [m.milk.qty, m.beans.qty, m['croissant-dough'].qty, m.samosa.qty]; })()")
        print('STOCK milk,beans,croissant,samosa', stock)
        print('LOGS', logs[:20])
        await ctx.close(); await b.close()
asyncio.run(main())
