import asyncio
from playwright.async_api import async_playwright
from _env import URL, launch_opts
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(**launch_opts())
        ctx = await b.new_context(viewport={'width': 1280, 'height': 860}, device_scale_factor=1)
        pg = await ctx.new_page()
        logs = []
        pg.on('console', lambda m: logs.append(m.type + ': ' + m.text) if m.type == 'error' else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERROR: ' + str(e)))
        await pg.goto(URL + '#staff')
        await pg.wait_for_timeout(2000)
        await pg.screenshot(path='shots/s0_lock.png')
        for k in '1239': await pg.click(f'[data-pin="{k}"]')
        await pg.wait_for_timeout(700)
        for k in '1234': await pg.click(f'[data-pin="{k}"]')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/s1_overview_empty.png')
        await pg.click('[data-a=sample]'); await pg.wait_for_timeout(500)
        await pg.click('.dialog-f .btn:not(.ghost)'); await pg.wait_for_timeout(3500)
        await pg.screenshot(path='shots/s2_overview.png', full_page=True)
        # place a portal order in another tab -> should appear on the board
        c = await ctx.new_page()
        await c.goto(URL + '#table-7'); await c.wait_for_timeout(2500)
        await c.click('button[data-inc="cappuccino"]'); await c.click('button[data-inc="samosa"]')
        await c.goto(URL + '#cart'); await c.wait_for_timeout(1200)
        await c.click('[data-pm=counter]'); await c.click('[data-act=place]'); await c.wait_for_timeout(2000)
        await pg.bring_to_front()
        await pg.goto(URL + '#staff-orders'); await pg.wait_for_timeout(2000)
        await pg.screenshot(path='shots/s3_orders.png')
        await pg.click('[data-next]'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/s3b_orders_after.png')
        await pg.goto(URL + '#staff-billing'); await pg.wait_for_timeout(4000)
        await pg.click('[data-padd="croissant"]'); await pg.click('[data-padd="cold-coffee"]'); await pg.click('[data-padd="cold-coffee"]')
        await pg.select_option('[data-ptable]', '4')
        await pg.fill('[data-pdisc]', '10')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='shots/s4_billing.png')
        await pg.click('[data-pay=cash]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/s5_cash.png')
        await pg.click('[data-quick]:last-child'); await pg.click('.dialog-f .btn.saffron'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/s6_receipt.png')
        await pg.click('.dialog-f .btn:last-child'); await pg.wait_for_timeout(500)
        # collect the waiting portal order
        await pg.click('[data-collect]'); await pg.wait_for_timeout(500)
        await pg.click('[data-cm=upi]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/s7_collect_upi.png')
        await pg.click('.dialog-f .btn.saffron'); await pg.wait_for_timeout(1200)
        await pg.click('.dialog-f .btn:last-child'); await pg.wait_for_timeout(400)
        for page in ['bills', 'menu', 'stock', 'reports', 'tables', 'setup']:
            await pg.goto(URL + '#staff-' + page); await pg.wait_for_timeout(3500 if page in ('menu',) else 1800)
            await pg.screenshot(path=f'shots/s8_{page}.png', full_page=(page in ('reports','stock')))
        await pg.goto(URL + '#staff-menu'); await pg.wait_for_timeout(1500)
        await pg.click('[data-dedit="cappuccino"]'); await pg.wait_for_timeout(3000)
        await pg.screenshot(path='shots/s9_editor.png')
        await pg.click('.dialog-f .btn:last-child'); await pg.wait_for_timeout(800)
        await pg.goto(URL + '#staff-stock'); await pg.wait_for_timeout(1500)
        await pg.click('[data-sbuy="mango"]'); await pg.wait_for_timeout(400)
        await pg.fill('[data-q]', '5'); await pg.click('.dialog-f .btn:last-child'); await pg.wait_for_timeout(1200)
        st = await pg.evaluate("(() => { const m = Data.derived().stockMap; const d = Data.derived().menuById['mango-lassi']; return [m.mango.qty, m.mango.state, Data.dishStatus(d, m, Data.state.settings, new Date()).ok]; })()")
        print('mango after purchase', st)
        n = await pg.evaluate("[Data.state.orders.length, Data.state.orders.filter(o=>!o.demo).map(o=>[o.id,o.status,o.pay.method,o.pay.status,o.total])]")
        print('orders', n)
        print('LOGS', logs[:20])
        await ctx.close(); await b.close()
asyncio.run(main())
