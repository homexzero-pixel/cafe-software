import asyncio
from playwright.async_api import async_playwright
from _env import URL, launch_opts
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(**launch_opts())
        ctx = await b.new_context(viewport={'width': 1200, 'height': 820})
        await ctx.add_init_script(path='test/mock_runtime.js')
        pg = await ctx.new_page()
        logs = []
        pg.on('console', lambda m: logs.append(m.type + ': ' + m.text) if m.type == 'error' else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERROR: ' + str(e)))
        await pg.goto(URL + '#staff'); await pg.wait_for_timeout(2500)
        print('mode', await pg.evaluate('Data.state.mode'), 'synced', await pg.evaluate('Data.state.synced'), 'menu', await pg.evaluate('Data.state.menu.length'))
        for k in '1234': await pg.click(f'[data-pin="{k}"]')
        await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/k0_empty_cloud.png')
        await pg.click('.banner [data-a=seed]'); await pg.wait_for_timeout(4000)
        print('after seed: menu', await pg.evaluate('Data.state.menu.length'), 'stock', await pg.evaluate('Data.state.stock.length'), 'writes', await pg.evaluate('window.__writes'))
        # customer order in cloud mode
        await pg.goto(URL + '#table-9'); await pg.wait_for_timeout(2500)
        await pg.click('button[data-inc="filter-kaapi"]'); await pg.click('button[data-inc="filter-kaapi"]'); await pg.click('button[data-inc="donut"]')
        await pg.goto(URL + '#cart'); await pg.wait_for_timeout(1500)
        await pg.click('[data-pm=counter]'); await pg.click('[data-act=place]'); await pg.wait_for_timeout(2500)
        o = await pg.evaluate("Data.state.orders.map(o => [o.id, o.no, o.inv, o.total, o.customer, o.status, o.pay.status])")
        print('orders', o)
        print('counter doc', await pg.evaluate("JSON.stringify(window.__store.get('meta/counter'))"))
        await pg.goto(URL + '#staff-orders'); await pg.wait_for_timeout(2000)
        await pg.click('[data-next]'); await pg.wait_for_timeout(1500)
        print('status after start', await pg.evaluate("Data.state.orders[0].status"), await pg.evaluate("Data.state.orders[0].log.length"))
        await pg.goto(URL + '#bills'); await pg.wait_for_timeout(1500)
        print('my bills rows', await pg.evaluate("document.querySelectorAll('.bill-row').length"))
        await pg.goto(URL + '#staff-setup'); await pg.wait_for_timeout(1500)
        await pg.click('[data-a=sample]'); await pg.wait_for_timeout(400); await pg.click('.dialog-f .btn:not(.ghost)'); await pg.wait_for_timeout(6000)
        print('after samples', await pg.evaluate('Data.state.orders.length'), 'counter', await pg.evaluate("JSON.stringify(window.__store.get('meta/counter'))"))
        await pg.goto(URL + '#staff-stock'); await pg.wait_for_timeout(1500)
        await pg.click('[data-scount="milk"]'); await pg.wait_for_timeout(300); await pg.fill('[data-q]', '12'); await pg.click('.dialog-f .btn:last-child'); await pg.wait_for_timeout(1500)
        print('milk after count (expect 12000)', await pg.evaluate("Data.derived().stockMap.milk.qty"), 'ledger', await pg.evaluate('Data.state.ledger.length'))
        await pg.goto(URL + '#staff-bills'); await pg.wait_for_timeout(1500)
        await pg.click('[data-a=bcsv]'); await pg.wait_for_timeout(800)
        print('download', await pg.evaluate('window.__saved'))
        await pg.goto(URL + '#staff-setup'); await pg.wait_for_timeout(1500)
        await pg.fill('input[name=upiId]', 'kaapimarble@okaxis'); await pg.fill('input[name=fssai]', '12345678901234')
        await pg.click('[data-a=ssave]'); await pg.wait_for_timeout(1200)
        print('settings', await pg.evaluate("JSON.stringify([Data.state.settings.upiId, Data.state.settings.fssai])"))
        print('LOGS', logs[:12])
        await ctx.close(); await b.close()
asyncio.run(main())
